// Creates the schema and default settings if missing. Safe to call repeatedly; startup code awaits it once.
let ready = null;
function init() {
  if (!ready) {
    ready = (async () => {
      const client = await pool.connect();
      try {
        // One connection holds the advisory lock so two app instances starting together don't race on DDL.
        await client.query('SELECT pg_advisory_lock(727001)');
        try {
          if (schema) await client.query(`CREATE SCHEMA IF NOT EXISTS ${schema}`);
          await client.query(SCHEMA_SQL);
          for (const [k, v] of Object.entries(DEFAULT_SETTINGS)) {
            await client.query('INSERT INTO settings (key, value) VALUES ($1, $2) ON CONFLICT (key) DO NOTHING', [k, v]);
          }
        } finally {
          await client.query('SELECT pg_advisory_unlock(727001)');
        }
      } finally {
        client.release();
      }
    })();
    ready.catch(() => { ready = null; });
  }
  return ready;
}

// Used by the test-suite: optionally drops the private schema, then closes all connections.
async function close({ dropSchema = false } = {}) {
  if (dropSchema && schema) await pool.query(`DROP SCHEMA IF EXISTS ${schema} CASCADE`);
  await pool.end();
}

const db = { all, get, run, insert, transaction, pool };

async function getSettings() {
  const out = {};
  for (const r of await all('SELECT key, value FROM settings')) out[r.key] = r.value;
  return out;
}
async function lowStockThreshold() {
  const n = parseInt((await getSettings()).low_stock_threshold, 10);
  return Number.isFinite(n) && n >= 0 ? n : 5;
}
async function wholesaleEnabled() {
  return (await getSettings()).wholesale_enabled !== 'false';
}

function slugify(s) {
  return String(s).toLowerCase().normalize('NFKD').replace(/[^\w\s-]/g, '').trim().replace(/[\s_]+/g, '-').replace(/-+/g, '-') || 'item';
}

module.exports = { db, init, close, DEFAULT_SETTINGS, getSettings, lowStockThreshold, wholesaleEnabled, slugify };
