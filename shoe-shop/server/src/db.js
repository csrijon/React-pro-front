const { Pool, types } = require('pg');
const { AsyncLocalStorage } = require('async_hooks');
const config = require('./config');

// COUNT()/SUM() come back as bigint (text) and NUMERIC as text; the API wants plain numbers.
types.setTypeParser(20, (v) => parseInt(v, 10));
types.setTypeParser(1700, (v) => parseFloat(v));
// Timestamps are sent to the client as 'YYYY-MM-DD HH:MM:SS' (UTC). The session timezone is forced to UTC below.
types.setTypeParser(1184, (v) => v.slice(0, 19));

const schema = config.dbSchema;
if (schema && !/^[a-z_][a-z0-9_]*$/i.test(schema)) throw new Error('DB_SCHEMA may only contain letters, digits and underscores');

const pool = new Pool({
  connectionString: config.databaseUrl,
  ssl: config.databaseSsl ? { rejectUnauthorized: false } : undefined,
  max: 10,
  options: `-c timezone=UTC${schema ? ` -c search_path=${schema},public` : ''}`,
});
pool.on('error', (err) => console.error('[pg] idle client error', err.message));

// Queries use "?" placeholders; they are converted to $1, $2, ... here.
const toPg = (sql) => { let i = 0; return sql.replace(/\?/g, () => `$${++i}`); };

// Inside db.transaction() every query automatically runs on the transaction's connection.
const txStore = new AsyncLocalStorage();
const executor = () => txStore.getStore() || pool;

const all = async (sql, ...args) => (await executor().query(toPg(sql), args)).rows;
const get = async (sql, ...args) => (await all(sql, ...args))[0];
// run(): { changes: affected rows, id: first column "id" of a RETURNING clause }
const run = async (sql, ...args) => {
  const r = await executor().query(toPg(sql), args);
  return { changes: r.rowCount, id: r.rows[0] ? r.rows[0].id : undefined };
};
const insert = async (sql, ...args) => (await run(`${sql} RETURNING id`, ...args)).id;

async function transaction(fn) {
  if (txStore.getStore()) return fn(); // already inside a transaction: join it
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    const result = await txStore.run(client, fn);
    await client.query('COMMIT');
    return result;
  } catch (err) {
    try { await client.query('ROLLBACK'); } catch { /* connection already broken */ }
    throw err;
  } finally {
    client.release();
  }
}

const SCHEMA_SQL = `
CREATE EXTENSION IF NOT EXISTS citext SCHEMA public;  -- case-insensitive text (usernames, SKUs, names)

CREATE TABLE IF NOT EXISTS users (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username      CITEXT NOT NULL UNIQUE,   -- admins: username, customers: mobile number
  password_hash TEXT NOT NULL,
  role          TEXT NOT NULL CHECK (role IN ('ADMIN','CUSTOMER')),
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS customers (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     INTEGER NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
  shop_name   TEXT NOT NULL,
  owner_name  TEXT NOT NULL,
  mobile      TEXT NOT NULL UNIQUE,
  email       TEXT,
  address     TEXT,
  status      TEXT NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','APPROVED','REJECTED','SUSPENDED')),
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_customers_status ON customers(status);

CREATE TABLE IF NOT EXISTS customer_approvals (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id INTEGER NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
  status      TEXT NOT NULL,
  admin_id    INTEGER REFERENCES users(id) ON DELETE SET NULL,
  note        TEXT,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS brands (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       CITEXT NOT NULL UNIQUE,
  slug       TEXT NOT NULL UNIQUE,
  logo_url   TEXT,
  active     INTEGER NOT NULL DEFAULT 1,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS categories (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  gender     TEXT NOT NULL CHECK (gender IN ('men','women','kids')),
  name       CITEXT NOT NULL,
  slug       TEXT NOT NULL,
  image_url  TEXT,
  active     INTEGER NOT NULL DEFAULT 1,
  sort_order INTEGER NOT NULL DEFAULT 0,
  UNIQUE (gender, slug),
  UNIQUE (gender, name)
);

CREATE TABLE IF NOT EXISTS subcategories (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id INTEGER NOT NULL REFERENCES categories(id) ON DELETE CASCADE,
  name        CITEXT NOT NULL,
  slug        TEXT NOT NULL,
  active      INTEGER NOT NULL DEFAULT 1,
  UNIQUE (category_id, slug),
  UNIQUE (category_id, name)
);

CREATE TABLE IF NOT EXISTS products (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name            TEXT NOT NULL,
  slug            TEXT NOT NULL UNIQUE,
  sku             CITEXT NOT NULL UNIQUE,
  brand_id        INTEGER NOT NULL REFERENCES brands(id) ON DELETE RESTRICT,
  category_id     INTEGER NOT NULL REFERENCES categories(id) ON DELETE RESTRICT,
  subcategory_id  INTEGER REFERENCES subcategories(id) ON DELETE SET NULL,
  gender          TEXT NOT NULL CHECK (gender IN ('men','women','kids')),
  description     TEXT NOT NULL DEFAULT '',
  mrp             DOUBLE PRECISION NOT NULL CHECK (mrp >= 0),
  wholesale_price DOUBLE PRECISION CHECK (wholesale_price IS NULL OR wholesale_price >= 0),
  featured        INTEGER NOT NULL DEFAULT 0,
  active          INTEGER NOT NULL DEFAULT 1,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_products_category ON products(category_id);
CREATE INDEX IF NOT EXISTS idx_products_brand ON products(brand_id);
CREATE INDEX IF NOT EXISTS idx_products_flags ON products(active, featured);

CREATE TABLE IF NOT EXISTS product_images (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  url        TEXT NOT NULL,
  position   INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_images_product ON product_images(product_id);

CREATE TABLE IF NOT EXISTS colors (
  id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name CITEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS sizes (
  id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  label CITEXT NOT NULL UNIQUE,
  sort  DOUBLE PRECISION NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS product_colors (
  product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  color_id   INTEGER NOT NULL REFERENCES colors(id) ON DELETE RESTRICT,
  PRIMARY KEY (product_id, color_id)
);

CREATE TABLE IF NOT EXISTS product_sizes (
  product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  size_id    INTEGER NOT NULL REFERENCES sizes(id) ON DELETE RESTRICT,
  PRIMARY KEY (product_id, size_id)
);

-- One row per Product -> Color -> Size. The only place stock quantities live.
CREATE TABLE IF NOT EXISTS inventory (
  product_id      INTEGER NOT NULL,
  color_id        INTEGER NOT NULL,
  size_id         INTEGER NOT NULL,
  quantity        INTEGER NOT NULL DEFAULT 0 CHECK (quantity >= 0),
  mrp             DOUBLE PRECISION CHECK (mrp IS NULL OR mrp >= 0),
  wholesale_price DOUBLE PRECISION CHECK (wholesale_price IS NULL OR wholesale_price >= 0),
  PRIMARY KEY (product_id, color_id, size_id),
  FOREIGN KEY (product_id, color_id) REFERENCES product_colors(product_id, color_id) ON DELETE CASCADE,
  FOREIGN KEY (product_id, size_id)  REFERENCES product_sizes(product_id, size_id)  ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_inventory_size ON inventory(size_id);
CREATE INDEX IF NOT EXISTS idx_inventory_color ON inventory(color_id);

CREATE TABLE IF NOT EXISTS settings (
  key   TEXT PRIMARY KEY,
  value TEXT NOT NULL DEFAULT ''
);

-- Purchase cost per pair (admin-only; never exposed on the storefront).
ALTER TABLE products ADD COLUMN IF NOT EXISTS cost_price DOUBLE PRECISION CHECK (cost_price IS NULL OR cost_price >= 0);

-- Append-only audit log of every stock change. Product/colour/size/admin are stored as text snapshots so the
-- history survives later edits and deletions.
CREATE TABLE IF NOT EXISTS stock_movements (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id     INTEGER REFERENCES products(id) ON DELETE SET NULL,
  product_name   TEXT NOT NULL,
  sku            TEXT NOT NULL,
  color          TEXT NOT NULL,
  size           TEXT NOT NULL,
  change         INTEGER NOT NULL,
  quantity_after INTEGER NOT NULL,
  type           TEXT NOT NULL CHECK (type IN ('INITIAL','RECEIVE','ADJUST','EDIT','REMOVED')),
  reason         TEXT NOT NULL DEFAULT '',
  note           TEXT NOT NULL DEFAULT '',
  admin_id       INTEGER REFERENCES users(id) ON DELETE SET NULL,
  admin_name     TEXT NOT NULL DEFAULT 'System',
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_movements_created ON stock_movements(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_movements_product ON stock_movements(product_id);
`;

